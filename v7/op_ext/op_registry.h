/* op_registry.h —— 值算子注册表接口（扩展点）
 *
 * SPDX-License-Identifier: GPL-3.0-or-later
 * SPDX-FileCopyrightText: 2026 haothtrteen <2557976190@qq.com>
 * 本文件是 GNU bash 的衍生作品，许可证由上游强制继承（不可更改）。
 * 分发内含魔改 bash 的产物时必须提供对应完整源码。
 *
 * ===========================================================================
 * 这是什么
 * ===========================================================================
 * V7 的 ISA 令牌化（L1-L6）解决的是「名字暴露」：命令名、关键字、变量名、
 * 路径、字符串字面量在产物里都是随机令牌。
 *
 * 但有一类逻辑它覆盖不到：**纯值运算**。
 *
 *   sum=$(( (a + b) * 7 ))        ← 算术，表达式本身仍是明文
 *   h=$(printf '%s' "$x" | sha256sum)  ← 哈希，管道和命令名也在明文里
 *
 * 本扩展点把这类运算搬到 C 层执行：
 *
 *   # 开发者这么写（原脚本）
 *   sum=$(( (a + b) * 7 ))
 *
 *   # 编译期 v7_isa_ops.py 翻译成
 *   v7p_x7k2m9q1=$(v7p_9yshhevga_ v7p_3f8a1c v7p_b5e2d7 v7p_7)
 *   #              ↑ 命令名令牌        ↑ 参数令牌（变量名 a / b）
 *
 *   # 运行期 C 层拦截 → 取值 → 算 → 写回
 *   # 全过程中「(a+b)*7」这段表达式文本从未存在于产物或内存
 *
 * ---------------------------------------------------------------------------
 * 为什么不需要写解析器
 * ---------------------------------------------------------------------------
 * 语法分析发生在**编译期**（tools/v7_isa_ops.py），运行期拿到的是
 * 结构化的（算子 id, 参数1, 参数2, ...），不是文本。所以本层只需实现
 * 「算子执行器」，不需要词法/语法分析。
 *
 * 这是它与"在 C 里重新实现 shell"的根本区别：
 *   重新实现 shell = 解析器 + 执行器    （巨大，且引入解析器攻击面）
 *   本扩展点       = 执行器（无解析器）  （小，且无解析器攻击面）
 *
 * ===========================================================================
 * 攻击面契约（实现算子前必须读）
 * ===========================================================================
 * 本层**不扩大解析器攻击面**（没有解析器），但确实引入三类新风险，
 * 每个算子实现者必须自行控制：
 *
 *   ① 参数越界      —— substr 的 offset/len 必须校验，否则读越界
 *   ② 整数溢出      —— 算术算子必须定义溢出行为（回绕 / 饱和 / 拒绝）
 *   ③ 缓冲长度      —— 输出必须显式限长，禁止 strcpy 家族
 *
 * 算子实现必须是**纯函数**：给定输入，结果确定，不读写任何 bash 状态
 * （除了下面 v7_op_arg_* / v7_op_ret_* 提供的接口）。
 * 凡是需要改变 shell 状态的（控制流、变量作用域、作业控制），**不要**做成算子。
 *
 * ===========================================================================
 * 边界声明（必读，否则会掉进工作量陷阱）
 * ===========================================================================
 * 本扩展点**只适用于纯值运算**，不适用于控制流。
 *
 * 原因（bash 架构决定，非实现缺陷）：
 *   bash 的控制流分派依赖 enum command_type（cm_if / cm_for / cm_while），
 *   该字段由词法 + 语法分析阶段填入，此阶段**必须面对明文 token**。
 *   把 if/for/while 搬到 C 层，等于在 C 里重新实现 bash 的分支栈、循环
 *   变量、break/continue 目标——即重新实现整个执行引擎。
 *
 * ⇒ 值算子：可扩展，推荐。
 *   控制流：是架构下限，加多少算子都无法改变。
 */

#ifndef V7_OP_REGISTRY_H
#define V7_OP_REGISTRY_H

#include <stddef.h>

/* ===================================================================
 * 返回值约定
 * =================================================================== */
#define V7_OP_OK        0    /* 成功 */
#define V7_OP_ERR_ARG   1    /* 参数非法（越界 / 格式错 / 数量不对） */
#define V7_OP_ERR_RANGE 2    /* 数值溢出 / 超出定义域 */
#define V7_OP_ERR_NOMEM 3    /* 分配失败 */
#define V7_OP_ERR_INTER 4    /* 内部错误 */

/* 输出缓冲上限。算子必须保证写入不超过此长度（含结尾 '\0'）。
 * 与 v7_echo_builtin 的 V7_ARG_BUF 保持同量级，便于栈上分配。 */
#define V7_OP_OUT_MAX   640

/* ===================================================================
 * 算子函数签名
 *
 *   args     : 参数数组（已由 C 层从 bash WORD_LIST 取出并令牌还原）
 *   nargs    : 参数个数
 *   out      : 输出缓冲（调用方提供，栈上，长度 >= V7_OP_OUT_MAX）
 *   outsz    : 输出缓冲实际大小
 *
 * 返回 V7_OP_OK 时，out 里必须是 '\0' 结尾的结果字符串。
 * 返回其它值时，out 内容被忽略（调用方按失败处理）。
 *
 * ⚠️ 契约：args 里的字符串是**调用方持有**的临时缓冲，算子**不得保存**
 *    任何指向它们的指针（返回后即被擦除）。
 * =================================================================== */
typedef int (*v7_op_fn) (const char *const *args, int nargs,
                         char *out, size_t outsz);

/* 算子表项。name 是**真名**（如 "v7op_add"），不是令牌 ——
 * 令牌 → 真名 的映射由 V7 的 L1/L2 令牌化层负责，与本表无关。 */
typedef struct {
    const char *name;      /* 算子真名（编译期由 v7_isa_ops.py 绑定到令牌） */
    v7_op_fn    fn;        /* 实现 */
    int         nargs_min; /* 参数个数下限（含） */
    int         nargs_max; /* 参数个数上限（含） */
    const char *help;      /* 一行说明（供 --help / 审计用） */
} v7_op_entry;

/* ===================================================================
 * 参数访问辅助（由 isa_ops.c 提供，算子实现直接调用）
 *
 * 这些函数的职责是「把 bash 变量的值安全地取到一个临时缓冲」，
 * 并统一处理令牌还原、引号剥离、长度校验。
 * =================================================================== */

/* 取第 i 个参数的字面值。返回 0 成功。
 * 结果写入 buf（不含引号），buf 由调用方提供栈上空间。 */
int  v7_op_arg_str  (const char *const *args, int nargs, int i,
                     char *buf, size_t bufsz);

/* 取第 i 个参数并按十进制解析为 long。返回 0 成功，非 0 解析失败。
 * 溢出返回 V7_OP_ERR_RANGE。 */
int  v7_op_arg_long (const char *const *args, int nargs, int i, long *out);

/* 写回输出。成功返回 V7_OP_OK；超长返回 V7_OP_ERR_ARG。 */
int  v7_op_ret_str  (char *out, size_t outsz, const char *s);

/* 写回一个 long。 */
int  v7_op_ret_long (char *out, size_t outsz, long v);

/* 十六进制编码 / 解码（供实现 hash/b64 一类算子复用，避免各写一份）。 */
int  v7_op_hex_encode (char *out, size_t outsz, const unsigned char *in, size_t n);
int  v7_op_hex_decode (unsigned char *out, size_t outsz, const char *hex);

/* 简易 SHA-256（复用 crypto_isa.h 的实现，单次，无流式）。
 * 写 32 字节到 out。 */
void v7_op_sha256 (const unsigned char *in, size_t n, unsigned char out[32]);

#endif /* V7_OP_REGISTRY_H */
